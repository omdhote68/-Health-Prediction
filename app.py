"""Health Prediction Application - Streamlit front end.

This file contains ONLY screen layout. All rules live in src/:
  validation.py -> checks the data      database.py -> SQLite
  ai_service.py -> Gemini API           patient_service.py -> ties them together

Run with:  streamlit run app.py
"""

import os
from pathlib import Path

import pandas as pd
import streamlit as st
from dotenv import load_dotenv

load_dotenv()  # reads GEMINI_API_KEY etc. from a local .env file (never committed)

from src import ai_service  # noqa: E402
from src.assessment_data import TEST_RECORDS  # noqa: E402
from src.database import PatientDatabase  # noqa: E402
from src.patient_service import (  # noqa: E402
    AI_SKIPPED,
    AI_SUCCESS,
    AI_UNAVAILABLE,
    PatientNotFoundError,
    PatientService,
    RAW_FIELDS,
)

BASE_DIR = Path(__file__).resolve().parent
DB_PATH = os.getenv("HEALTH_DB_PATH") or str(BASE_DIR / "data" / "patients.db")

FIELD_LABELS = {
    "full_name": "Full Name",
    "date_of_birth": "Date of Birth",
    "email": "Email Address",
    "glucose": "Glucose",
    "haemoglobin": "Haemoglobin",
    "cholesterol": "Cholesterol",
}
FIELD_HELP = {
    "date_of_birth": "dd/mm/yyyy (dd.mm.yyyy also accepted)",
    "glucose": "Number, units not specified",
    "haemoglobin": "Number, units not specified",
    "cholesterol": "Number, units not specified",
}

st.set_page_config(page_title="Health Prediction App", page_icon="🩺", layout="wide")


@st.cache_resource
def get_service() -> PatientService:
    return PatientService(PatientDatabase(DB_PATH))


service = get_service()


# ---------------------------------------------------------------- helpers ---
def flash(kind: str, message: str) -> None:
    """Remember a message across st.rerun() so it shows after the page reloads."""
    st.session_state["flash"] = (kind, message)


def show_flash() -> None:
    kind, message = st.session_state.pop("flash", (None, None))
    if kind:
        getattr(st, kind)(message)


def status_label(record: dict) -> str:
    return "✅ Valid" if record["validation_status"] == "valid" else "❌ Invalid"


def duplicate_label(record: dict) -> str:
    return f"⚠️ Duplicate of #{record['duplicate_of']}" if record["duplicate_of"] else "—"


def ai_label(record: dict) -> str:
    return {
        AI_SUCCESS: "🤖 Generated by Gemini API",
        AI_UNAVAILABLE: "⛔ AI analysis unavailable",
        AI_SKIPPED: "⏭️ Not sent (invalid record)",
    }.get(record["ai_status"], record["ai_status"])


def records_dataframe(records: list[dict]) -> pd.DataFrame:
    return pd.DataFrame(
        [
            {
                "ID": r["id"],
                "Full Name": r["full_name"],
                "Date of Birth": r["date_of_birth"],
                "Email": r["email"],
                "Glucose": r["glucose"],
                "Haemoglobin": r["haemoglobin"],
                "Cholesterol": r["cholesterol"],
                "Remarks": r["remarks"],
                "Validation Status": status_label(r),
                "Duplicate": duplicate_label(r),
                "Remarks Source": ai_label(r),
                "Validation Errors": " | ".join(r["validation_errors"]),
            }
            for r in records
        ]
    )


def show_records_table(records: list[dict]) -> None:
    if not records:
        st.info("No patient records yet. Use **Add Patient** to create one.")
        return
    st.dataframe(records_dataframe(records), hide_index=True)


def patient_option_label(record: dict) -> str:
    return f"#{record['id']} - {record['full_name']} - {record['email']}"


def show_outcome(summary: dict) -> None:
    """Explain what happened to a record that was just saved."""
    name = summary["name"]
    if summary["valid"]:
        st.success(f"Record #{summary['id']} for **{name}** saved. All validation checks passed.")
    else:
        st.error(
            f"Record #{summary['id']} for **{name}** was saved but flagged **INVALID** "
            "and was NOT sent to the AI. Reasons:"
        )
        for error in summary["errors"]:
            st.markdown(f"- {error}")
    if summary["duplicate_of"]:
        st.warning(f"⚠️ Possible duplicate: identical to record #{summary['duplicate_of']}. Both are kept.")
    if summary["ai_called"]:
        if summary["ai_ok"]:
            st.info("🤖 Remarks were generated by the external Gemini API.")
        else:
            st.warning(f"⛔ AI analysis unavailable: {summary['ai_error']} The record itself was saved.")
    with st.expander("Remarks stored for this record", expanded=True):
        st.write(summary["remarks"])


def summarise(outcome) -> dict:
    rec = outcome.record
    return {
        "id": rec["id"],
        "name": rec["full_name"],
        "valid": outcome.validation.is_valid,
        "errors": rec["validation_errors"],
        "duplicate_of": rec["duplicate_of"],
        "ai_called": outcome.ai is not None,
        "ai_ok": bool(outcome.ai and outcome.ai.ok),
        "ai_error": outcome.ai.error if outcome.ai else "",
        "remarks": rec["remarks"],
    }


# ------------------------------------------------------------------ pages ---
def page_dashboard() -> None:
    st.header("Dashboard")
    stats = service.get_stats()
    c1, c2, c3 = st.columns(3)
    c1.metric("Total records", stats["total"])
    c2.metric("Valid records", stats["valid"])
    c3.metric("Invalid records", stats["invalid"])
    c4, c5, c6 = st.columns(3)
    c4.metric("Duplicate records", stats["duplicates"])
    c5.metric("AI analyses successful", stats["ai_success"])
    c6.metric("AI analyses unavailable", stats["ai_unavailable"])
    st.caption(f"{stats['ai_skipped']} invalid record(s) were deliberately not sent to the AI.")

    if ai_service.api_key_configured():
        st.success(f"Gemini API key detected (model: {ai_service.get_model_name()}).")
    else:
        st.warning("No Gemini API key configured. Records can be saved, but remarks will say 'AI analysis unavailable'.")

    st.subheader("Latest records")
    show_records_table(service.list_patients()[-5:])


def page_add() -> None:
    st.header("Add Patient")
    show_flash()
    n = st.session_state.setdefault("add_form_n", 0)
    keys = {f: f"add_{f}_{n}" for f in RAW_FIELDS}

    with st.expander("Assessment test data (Gokul Infocare) - pre-fill the form with an exact supplied record"):
        st.caption("This only types the supplied values into the form for you. You still press Save, and nothing is corrected.")
        choice = st.selectbox(
            "Test record",
            range(len(TEST_RECORDS)),
            format_func=lambda i: f"Test {i + 1}: {TEST_RECORDS[i]['full_name']} / {TEST_RECORDS[i]['date_of_birth']} / {TEST_RECORDS[i]['email']}",
            key="add_test_choice",
        )

        def prefill(index: int, field_keys: dict) -> None:
            for f in RAW_FIELDS:
                st.session_state[field_keys[f]] = TEST_RECORDS[index][f]

        st.button("Fill form with this record", on_click=prefill, args=(choice, keys))

    with st.form(f"add_form_{n}"):
        values = {
            f: st.text_input(FIELD_LABELS[f], key=keys[f], help=FIELD_HELP.get(f))
            for f in RAW_FIELDS
        }
        submitted = st.form_submit_button("Save patient", type="primary")

    if submitted:
        with st.spinner("Validating and saving (valid records are analysed by the AI)..."):
            outcome = service.create_patient(values)
        st.session_state["last_add_result"] = summarise(outcome)
        st.session_state["add_form_n"] = n + 1  # fresh, empty form next time
        st.rerun()

    if "last_add_result" in st.session_state:
        st.divider()
        st.subheader("Result of last submission")
        show_outcome(st.session_state["last_add_result"])


def page_records() -> None:
    st.header("Patient Records")
    show_flash()
    col_search, col_status = st.columns([3, 1])
    search = col_search.text_input("Search by name or email", placeholder="e.g. robyn or gmail")
    status_choice = col_status.selectbox("Show", ["All", "Valid only", "Invalid only"])
    status = {"All": None, "Valid only": "valid", "Invalid only": "invalid"}[status_choice]

    records = service.list_patients(search, status)
    st.caption(f"Showing {len(records)} record(s). Invalid and duplicate records are included.")
    show_records_table(records)

    if records:
        st.subheader("Full remarks")
        chosen = st.selectbox("Select a record", records, format_func=patient_option_label, key="records_detail")
        st.markdown(f"**Validation:** {status_label(chosen)} &nbsp; **Duplicate:** {duplicate_label(chosen)} &nbsp; **Remarks source:** {ai_label(chosen)}")
        for error in chosen["validation_errors"]:
            st.markdown(f"- ❌ {error}")
        st.write(chosen["remarks"])


def page_update() -> None:
    st.header("Update Patient")
    show_flash()
    records = service.list_patients()
    if not records:
        st.info("No patient records to update.")
        return

    chosen = st.selectbox("Select the patient to edit", records, format_func=patient_option_label, key="update_choice")
    pid = chosen["id"]
    st.caption("Editing changes the existing record - it does not create a new one.")

    with st.form(f"update_form_{pid}"):
        values = {
            f: st.text_input(FIELD_LABELS[f], value=chosen[f], key=f"upd_{f}_{pid}", help=FIELD_HELP.get(f))
            for f in RAW_FIELDS
        }
        submitted = st.form_submit_button("Save changes", type="primary")

    if submitted:
        try:
            with st.spinner("Saving..."):
                outcome = service.update_patient(pid, values)
        except PatientNotFoundError:
            st.error("That record no longer exists.")
            return
        st.session_state["last_update_result"] = summarise(outcome)
        flash("success", f"Record #{pid} updated.")
        st.rerun()

    result = st.session_state.get("last_update_result")
    if result:
        st.divider()
        st.subheader("Last update")
        show_outcome(result)
        updated = service.db.get_patient(result["id"])
        if updated:
            st.markdown("**Record as now stored:**")
            show_records_table([updated])


def page_delete() -> None:
    st.header("Delete Patient")
    show_flash()
    records = service.list_patients()
    if not records:
        st.info("No patient records to delete.")
        return

    chosen = st.selectbox("Select the patient to delete", records, format_func=patient_option_label, key="delete_choice")
    pid = chosen["id"]

    if st.button("Delete this record", type="primary"):
        st.session_state["pending_delete"] = pid

    if st.session_state.get("pending_delete") == pid:
        st.warning(f"**Are you sure?** This will permanently delete record #{pid} ({chosen['full_name']}, {chosen['email']}).")
        yes, no, _ = st.columns([1, 1, 4])
        if yes.button("Yes, delete it"):
            try:
                service.delete_patient(pid)
                flash("success", f"Record #{pid} ({chosen['full_name']}) deleted. Remaining records are shown below.")
            except PatientNotFoundError:
                flash("error", "That record was already deleted.")
            st.session_state.pop("pending_delete", None)
            st.rerun()
        if no.button("Cancel"):
            st.session_state.pop("pending_delete", None)
            st.rerun()
    elif "pending_delete" in st.session_state:
        st.session_state.pop("pending_delete")  # selection changed; drop stale confirmation

    st.divider()
    st.subheader("All remaining records")
    show_records_table(service.list_patients())


def page_ai() -> None:
    st.header("API / AI Analysis")
    st.markdown(
        "Valid records are sent to the **Google Gemini API** (`generate_content`). Only the age "
        "(derived from date of birth) and the three blood values are sent - **never the name or email**."
    )
    c1, c2 = st.columns(2)
    c1.metric("API key configured", "Yes" if ai_service.api_key_configured() else "No")
    c2.metric("Model", ai_service.get_model_name())
    st.caption("The key itself is never displayed. Set it in your local .env file (see README).")

    st.subheader("Test the connection")
    if st.button("Send a tiny test request to Gemini"):
        with st.spinner("Contacting Gemini..."):
            result = ai_service.check_connection()
        if result.ok:
            st.success(f"Gemini API responded using model {result.model}.")
        else:
            st.error(f"Could not reach Gemini: {result.error}")

    st.subheader("Retry unavailable analyses")
    pending = [r for r in service.list_patients() if r["ai_status"] == AI_UNAVAILABLE]
    if not pending:
        st.info("No records are waiting for AI analysis.")
    else:
        st.write(f"{len(pending)} valid record(s) have no AI analysis because the API call failed earlier.")
        show_records_table(pending)
        if st.button("Retry AI analysis for these records"):
            done = failed = 0
            with st.spinner("Calling Gemini..."):
                for record in pending:
                    outcome = service.retry_ai(record["id"])
                    if outcome.ai and outcome.ai.ok:
                        done += 1
                    else:
                        failed += 1
            flash("success" if not failed else "warning", f"Retry finished: {done} succeeded, {failed} still unavailable.")
            st.rerun()
    show_flash()


